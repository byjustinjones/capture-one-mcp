#!/usr/bin/env node
/**
 * Derive per-property value ranges from the round-trip probe report.
 *
 * The sdef declares no ranges at all, but Capture One rejects out-of-range
 * writes with an explicit message ("Cannot set this value above 4."), so the
 * probe harness recovers the real limits from the app itself.
 *
 *   node scripts/verify-adjustments.mjs           # produces the report
 *   node scripts/gen-adjustment-ranges.mjs > src/co/adjustment-ranges.ts
 */
import { readFileSync } from "node:fs";

const report = JSON.parse(readFileSync("docs/adjustment-round-trip.json", "utf8"));

/** Only the discrete-set form of the message is trusted; the numeric bounds it
 *  reports are demonstrably wrong for some properties. */
function parseAllowed(msg) {
  if (!msg) return null;
  const m = msg.match(/other than\s+(.+?)\.?$/i);
  if (!m) return null;
  const vals = m[1].replace(/,?\s+or\s+/g, ", ").split(/,\s*/).map(Number).filter((n) => !Number.isNaN(n));
  return vals.length ? vals : null;
}

/** Bisection converges from inside the valid interval, so a bound lands a hair
 *  short of the real limit (3.9999722 for 4). Snap to a round number when the
 *  gap is within the search tolerance. */
function tidy(v) {
  if (v === null || v === undefined) return undefined;
  for (const step of [1, 0.5, 0.1]) {
    const snapped = Math.round(v / step) * step;
    if (Math.abs(snapped - v) <= Math.max(1e-3, Math.abs(v) * 2e-5)) {
      return Number(snapped.toFixed(4));
    }
  }
  return Number(v.toFixed(4));
}

const out = {};
for (const r of report) {
  const entry = {};
  const allowed = parseAllowed(r.rejectionMessage);
  if (allowed) {
    entry.allowed = allowed;
  } else if (r.boundsUnreliable) {
    // Bounds could not be measured; let Capture One clamp rather than invent a
    // limit that would reject legitimate values.
    if (r.clampsHigh || r.status === "SILENT-NOOP") entry.modular = true;
  } else {
    const min = tidy(r.minAccepted);
    const max = tidy(r.maxAccepted);
    if (min !== undefined) entry.min = min;
    if (max !== undefined) entry.max = max;
  }
  if (Object.keys(entry).length) out[r.param] = entry;
}

console.log("// GENERATED by scripts/gen-adjustment-ranges.mjs from docs/adjustment-round-trip.json.");
console.log("// Ranges are found by BISECTING against the live app, not by parsing its error text:");
console.log("// level_highlight_rgb accepts 0..255 while reporting 'Cannot set this value above 1.'");
console.log("// The dictionary declares no ranges at all. Do not hand-edit.\n");
console.log("export interface AdjustmentRange {");
console.log("  min?: number;");
console.log("  max?: number;");
console.log("  /** Discrete values, where the property accepts only a fixed set. */");
console.log("  allowed?: readonly number[];");
console.log("  /** Modular properties that wrap rather than clamp (the colour-balance hues);");
console.log("   *  their bounds could not be measured, so they are not range-validated. */");
console.log("  modular?: boolean;");
console.log("}\n");
console.log("export const ADJUSTMENT_RANGES: Readonly<Record<string, AdjustmentRange>> = {");
for (const [k, v] of Object.entries(out)) {
  const parts = [];
  if (v.min !== undefined) parts.push(`min: ${v.min}`);
  if (v.max !== undefined) parts.push(`max: ${v.max}`);
  if (v.allowed) parts.push(`allowed: [${v.allowed.join(", ")}] as const`);
  if (v.modular) parts.push("modular: true");
  console.log(`  ${JSON.stringify(k)}: { ${parts.join(", ")} },`);
}
console.log("};");
